import html2canvas from 'html2canvas';
import { jsPDF } from 'jspdf';

export interface PDFReportData {
  datasetName: string;
  dashboardName: string;
  category: string;
  businessDomain: string;
  readinessScore: number;
  qualityScore: number;
  version: string;
  executiveSummary?: string;
  recommendations?: string[];
  statistics?: {
    rowCount: number;
    columnCount: number;
    measures: number;
    dimensions: number;
  };
  kpis?: Array<{ name: string; value: string | number }>;
}

/**
 * Captures an HTML element and compiles it into a presentation-quality business report PDF.
 */
export async function exportElementToPDF(
  elementId: string,
  filename: string,
  landscape: boolean = false,
  metadata: PDFReportData,
  progressCallback?: (stage: string) => void
) {
  const element = document.getElementById(elementId);
  if (!element) {
    console.error(`[PDF Export] Element with id "${elementId}" not found.`);
    return;
  }

  // 1. Preparing & waiting for animations to complete
  progressCallback?.('Loading Charts & Widgets...');
  await new Promise((resolve) => setTimeout(resolve, 1500));

  // 2. Hide control buttons from the screenshot
  progressCallback?.('Capturing Dashboard Layout...');
  const styleEl = document.createElement('style');
  styleEl.innerHTML = '.no-print-pdf { display: none !important; }';
  document.head.appendChild(styleEl);

  let canvas: HTMLCanvasElement;
  try {
    canvas = await html2canvas(element, {
      scale: 2.2, // 300 DPI high resolution
      useCORS: true,
      allowTaint: true,
      logging: false,
      backgroundColor: '#0f172a',
    });
  } finally {
    document.head.removeChild(styleEl);
  }

  progressCallback?.('Generating Professional Layout...');

  // Page orientation & sizes
  const orientation = landscape ? 'landscape' : 'portrait';
  const doc = new jsPDF({
    orientation,
    unit: 'mm',
    format: 'a4',
  });

  const pdfWidth = landscape ? 297 : 210;
  const pdfHeight = landscape ? 210 : 297;

  // Colors
  const darkBlue = '#1e293b';
  const lightGrey = '#f8fafc';
  const blue = '#3b82f6';
  const green = '#10b981';
  const textDark = '#0f172a';
  const textMuted = '#64748b';

  // Helper: Draw header on pages (excluding cover)
  const drawHeader = (_pageNum: number, title: string) => {
    doc.setFillColor(darkBlue);
    doc.rect(0, 0, pdfWidth, 20, 'F');
    doc.setTextColor('#ffffff');
    doc.setFont('Helvetica', 'bold');
    doc.setFontSize(10);
    doc.text('AUTOMATED BUSINESS ANALYTICS', 15, 12);
    
    doc.setFontSize(8);
    doc.setTextColor('#94a3b8');
    doc.text(title.toUpperCase(), pdfWidth - 15, 12, { align: 'right' });
  };

  // Helper: Draw footer on pages
  const drawFooter = (pageNum: number) => {
    doc.setDrawColor('#e2e8f0');
    doc.line(15, pdfHeight - 15, pdfWidth - 15, pdfHeight - 15);
    doc.setFont('Helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(textMuted);
    doc.text('Generated by InsightNexus: An Intelligent Platform for Integrated Business Analytics', 15, pdfHeight - 10);
    doc.text(`Page ${pageNum}`, pdfWidth - 15, pdfHeight - 10, { align: 'right' });
  };

  // ================= PAGE 1: COVER PAGE =================
  progressCallback?.('Assembling Cover Section...');
  // Banner background
  doc.setFillColor(darkBlue);
  doc.rect(0, 0, pdfWidth, pdfHeight * 0.4, 'F');

  // Title
  doc.setTextColor('#ffffff');
  doc.setFont('Helvetica', 'bold');
  doc.setFontSize(22);
  doc.text('AUTOMATED BUSINESS ANALYTICS REPORT', 15, 45);

  doc.setFont('Helvetica', 'normal');
  doc.setFontSize(12);
  doc.setTextColor('#94a3b8');
  doc.text('Consolidated Data Health & Readiness Dossier', 15, 55);

  // Metadata Card
  doc.setFillColor(lightGrey);
  doc.setDrawColor('#cbd5e1');
  doc.roundedRect(15, pdfHeight * 0.45, pdfWidth - 30, 95, 4, 4, 'FD');

  doc.setFont('Helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(textDark);
  doc.text('REPORT INFORMATION', 25, (pdfHeight * 0.45) + 12);

  const drawRow = (label: string, value: string, yOffset: number) => {
    doc.setFont('Helvetica', 'bold');
    doc.setTextColor(textMuted);
    doc.text(label, 25, yOffset);
    doc.setFont('Helvetica', 'normal');
    doc.setTextColor(textDark);
    doc.text(value, 95, yOffset);
  };

  const startY = (pdfHeight * 0.45) + 25;
  drawRow('Dataset Ingested:', metadata.datasetName, startY);
  drawRow('Dashboard Target:', metadata.dashboardName || 'N/A', startY + 10);
  drawRow('Business Domain:', metadata.businessDomain || 'Generic Analytics', startY + 20);
  drawRow('Report Category:', metadata.category || 'General', startY + 30);
  drawRow('Report Version:', `v${metadata.version || '1.0'}.0`, startY + 40);
  drawRow('Date Generated:', new Date().toLocaleString(), startY + 50);

  // Confidential notice
  doc.setFontSize(7.5);
  doc.setTextColor(textMuted);
  doc.text('CONFIDENTIAL • REPORT INTENDED FOR PROJECT STAKEHOLDERS', pdfWidth / 2, pdfHeight - 20, { align: 'center' });

  // ================= PAGE 2: EXEC SUMMARY & STATS =================
  progressCallback?.('Formatting Executive Summary...');
  doc.addPage();
  drawHeader(2, 'Executive Summary & Metrics');

  doc.setFont('Helvetica', 'bold');
  doc.setFontSize(12);
  if (landscape) {
    // Landscape Layout (Max height 210, footer at 195)
    doc.setFont('Helvetica', 'bold');
    doc.setFontSize(11);
    doc.setTextColor(darkBlue);
    doc.text('1. EXECUTIVE SUMMARY', 15, 30);

    doc.setFont('Helvetica', 'normal');
    doc.setFontSize(9);
    doc.setTextColor('#334155');
    const summary = metadata.executiveSummary || 
      `The ingestion of dataset "${metadata.datasetName}" completed successfully. System heuristics resolved column schemas into logical dimensions and measures.`;
    doc.text(summary, 15, 36, { maxWidth: pdfWidth - 30, align: 'justify' });

    // Side-by-Side: Scores (Left) and Ingestion Profile Statistics (Right)
    doc.setFillColor('#eff6ff');
    doc.roundedRect(15, 65, 60, 25, 2, 2, 'F');
    doc.setFont('Helvetica', 'bold');
    doc.setFontSize(7.5);
    doc.setTextColor(blue);
    doc.text('READINESS SCORE', 20, 72);
    doc.setFontSize(14);
    doc.text(`${metadata.readinessScore}%`, 20, 84);

    doc.setFillColor('#ecfdf5');
    doc.roundedRect(80, 65, 60, 25, 2, 2, 'F');
    doc.setFont('Helvetica', 'bold');
    doc.setFontSize(7.5);
    doc.setTextColor(green);
    doc.text('QUALITY SCORE', 85, 72);
    doc.setFontSize(14);
    doc.text(`${metadata.qualityScore}%`, 85, 84);

    // Ingestion Stats
    doc.setFont('Helvetica', 'bold');
    doc.setFontSize(11);
    doc.setTextColor(darkBlue);
    doc.text('2. INGESTION PROFILE STATISTICS', 155, 60);

    const stats = metadata.statistics || { rowCount: 0, columnCount: 0, measures: 0, dimensions: 0 };
    const statBoxW = (pdfWidth - 170) / 2;

    const drawStatBox = (x: number, y: number, label: string, val: string) => {
      doc.setFillColor('#f8fafc');
      doc.setDrawColor('#e2e8f0');
      doc.roundedRect(x, y, statBoxW, 18, 1.5, 1.5, 'FD');
      doc.setFont('Helvetica', 'normal');
      doc.setFontSize(7);
      doc.setTextColor(textMuted);
      doc.text(label.toUpperCase(), x + 4, y + 6);
      doc.setFont('Helvetica', 'bold');
      doc.setFontSize(10);
      doc.setTextColor(textDark);
      doc.text(val, x + 4, y + 13);
    };

    drawStatBox(155, 65, 'Total Rows', stats.rowCount.toLocaleString());
    drawStatBox(155 + statBoxW + 4, 65, 'Total Columns', stats.columnCount.toString());
    drawStatBox(155, 87, 'Metrics/Measures', stats.measures.toString());
    drawStatBox(155 + statBoxW + 4, 87, 'Dimensions', stats.dimensions.toString());

    // KPIs / Snapshots at the bottom
    if (metadata.kpis && metadata.kpis.length > 0) {
      doc.setFont('Helvetica', 'bold');
      doc.setFontSize(11);
      doc.setTextColor(darkBlue);
      doc.text('3. METRIC SNAPSHOTS', 15, 110);

      let kpiY = 118;
      metadata.kpis.slice(0, 6).forEach((kpi) => {
        doc.setFont('Helvetica', 'bold');
        doc.setFontSize(8);
        doc.setTextColor(textMuted);
        doc.text(kpi.name, 15, kpiY);
        doc.setFont('Helvetica', 'bold');
        doc.setTextColor(textDark);
        doc.text(String(kpi.value), pdfWidth - 15, kpiY, { align: 'right' });
        doc.setDrawColor('#f1f5f9');
        doc.line(15, kpiY + 2, pdfWidth - 15, kpiY + 2);
        kpiY += 7;
      });
    }

  } else {
    // Portrait Layout (Max height 297, footer at 282)
    doc.setFont('Helvetica', 'bold');
    doc.setFontSize(12);
    doc.setTextColor(darkBlue);
    doc.text('1. EXECUTIVE SUMMARY', 15, 32);

    doc.setFont('Helvetica', 'normal');
    doc.setFontSize(9.5);
    doc.setTextColor('#334155');
    const summary = metadata.executiveSummary || 
      `The ingestion of dataset "${metadata.datasetName}" completed successfully. System heuristics and auto-profiling scripts ran analysis modules to establish suitability parameters. Column schemas were resolved into logical dimensions and measures.`;
    doc.text(summary, 15, 40, { maxWidth: pdfWidth - 30, align: 'justify' });

    // Scores
    doc.setFillColor('#eff6ff');
    doc.roundedRect(15, 85, (pdfWidth / 2) - 20, 35, 3, 3, 'F');
    doc.setFont('Helvetica', 'bold');
    doc.setFontSize(9);
    doc.setTextColor(blue);
    doc.text('ANALYTICS READINESS SCORE', 22, 95);
    doc.setFontSize(20);
    doc.text(`${metadata.readinessScore}%`, 22, 112);

    doc.setFillColor('#ecfdf5');
    doc.roundedRect((pdfWidth / 2) + 5, 85, (pdfWidth / 2) - 20, 35, 3, 3, 'F');
    doc.setFont('Helvetica', 'bold');
    doc.setFontSize(9);
    doc.setTextColor(green);
    doc.text('DATA QUALITY HEALTH', (pdfWidth / 2) + 12, 95);
    doc.setFontSize(20);
    doc.text(`${metadata.qualityScore}%`, (pdfWidth / 2) + 12, 112);

    // Stats Grid
    doc.setFont('Helvetica', 'bold');
    doc.setFontSize(12);
    doc.setTextColor(darkBlue);
    doc.text('2. INGESTION PROFILE STATISTICS', 15, 137);

    const stats = metadata.statistics || { rowCount: 0, columnCount: 0, measures: 0, dimensions: 0 };
    const statBoxW = (pdfWidth - 45) / 4;

    const drawStatBox = (x: number, y: number, label: string, val: string) => {
      doc.setFillColor('#f8fafc');
      doc.setDrawColor('#e2e8f0');
      doc.roundedRect(x, y, statBoxW, 25, 2, 2, 'FD');
      doc.setFont('Helvetica', 'normal');
      doc.setFontSize(7.5);
      doc.setTextColor(textMuted);
      doc.text(label.toUpperCase(), x + 5, y + 8);
      doc.setFont('Helvetica', 'bold');
      doc.setFontSize(11);
      doc.setTextColor(textDark);
      doc.text(val, x + 5, y + 18);
    };

    drawStatBox(15, 145, 'Total Rows', stats.rowCount.toLocaleString());
    drawStatBox(15 + statBoxW + 5, 145, 'Total Columns', stats.columnCount.toString());
    drawStatBox(15 + (statBoxW * 2) + 10, 145, 'Metrics/Measures', stats.measures.toString());
    drawStatBox(15 + (statBoxW * 3) + 15, 145, 'Dimensions', stats.dimensions.toString());

    // KPIs
    if (metadata.kpis && metadata.kpis.length > 0) {
      doc.setFont('Helvetica', 'bold');
      doc.setFontSize(12);
      doc.setTextColor(darkBlue);
      doc.text('3. METRIC SNAPSHOTS', 15, 187);

      let kpiY = 195;
      metadata.kpis.slice(0, 5).forEach((kpi) => {
        doc.setFont('Helvetica', 'bold');
        doc.setFontSize(8.5);
        doc.setTextColor(textMuted);
        doc.text(kpi.name, 15, kpiY);
        doc.setFont('Helvetica', 'bold');
        doc.setTextColor(textDark);
        doc.text(String(kpi.value), pdfWidth - 25, kpiY, { align: 'right' });
        doc.setDrawColor('#f1f5f9');
        doc.line(15, kpiY + 2, pdfWidth - 15, kpiY + 2);
        kpiY += 8;
      });
    }
  }

  drawFooter(2);

  // ================= PAGE 3+: WYSIWYG SLICED CAPTURE PREVIEW =================
  progressCallback?.('Slicing and Embedding Charts...');

  const margin = 15;
  const printWidth = pdfWidth - (margin * 2);
  const printHeightLimit = pdfHeight - 50;

  // Scale factor: Canvas units to mm on the page
  const scale = printWidth / canvas.width;

  // Slicing algorithm
  let sourceY = 0;
  let pageIndex = 3;

  while (sourceY < canvas.height) {
    const remainingHeightInMM = (canvas.height - sourceY) * scale;
    const sliceHeightInMM = Math.min(printHeightLimit, remainingHeightInMM);
    const sliceHeightInPX = sliceHeightInMM / scale;

    // Create a temporary slice canvas
    const sliceCanvas = document.createElement('canvas');
    sliceCanvas.width = canvas.width;
    sliceCanvas.height = sliceHeightInPX;

    const ctx = sliceCanvas.getContext('2d');
    if (ctx) {
      ctx.drawImage(
        canvas,
        0, sourceY, canvas.width, sliceHeightInPX,
        0, 0, canvas.width, sliceHeightInPX
      );
    }

    // Add page
    doc.addPage();
    drawHeader(pageIndex, 'Dashboard View Details');

    const imgSliceData = sliceCanvas.toDataURL('image/png');
    
    // Add nice border framing container
    doc.setDrawColor('#cbd5e1');
    doc.setFillColor('#0f172a');
    doc.roundedRect(margin - 1, 24, printWidth + 2, sliceHeightInMM + 2, 2, 2, 'FD');
    
    doc.addImage(imgSliceData, 'PNG', margin, 25, printWidth, sliceHeightInMM, undefined, 'FAST');
    drawFooter(pageIndex);

    sourceY += sliceHeightInPX;
    pageIndex++;
  }

  // ================= PAGE N: RECOMMENDATIONS =================
  if (metadata.recommendations && metadata.recommendations.length > 0) {
    progressCallback?.('Formatting Insights & Details...');
    doc.addPage();
    drawHeader(pageIndex, 'Insights & Recommendations');

    doc.setFont('Helvetica', 'bold');
    doc.setFontSize(12);
    doc.setTextColor(darkBlue);
    doc.text('4. STRATEGIC RECOMMENDATIONS', 15, 32);

    let recY = 42;
    metadata.recommendations.forEach((rec) => {
      doc.setFillColor(blue);
      doc.circle(18, recY - 1.5, 1.5, 'F');
      doc.setFont('Helvetica', 'normal');
      doc.setFontSize(9);
      doc.setTextColor('#334155');
      doc.text(rec, 24, recY, { maxWidth: pdfWidth - 40, align: 'justify' });
      
      const lines = doc.splitTextToSize(rec, pdfWidth - 40);
      recY += (lines.length * 5) + 6;
    });

    drawFooter(pageIndex);
  }

  progressCallback?.('Downloading Report...');
  doc.save(filename.toLowerCase().endsWith('.pdf') ? filename : `${filename}.pdf`);
}
